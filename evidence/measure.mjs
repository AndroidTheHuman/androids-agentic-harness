// Recomputes every number the case study and resume cite, from the game repo.
// Read-only: runs git and reads files; writes nothing. Ledger costs use evidence/game-repriced.json
// (from evidence/reprice.mjs) when it exists, and refuse one made at another game commit.
// Usage: node evidence/measure.mjs "<path to infinity autobattler>" > evidence/NUMBERS.md

import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const repo = process.argv[2];
if (!repo || !existsSync(join(repo, '.git'))) {
  console.error('usage: node evidence/measure.mjs <game repo path>');
  process.exit(2);
}

const git = (...args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8', maxBuffer: 1 << 28 });
const files = (...globs) => git('ls-files', '--', ...globs).split('\n').filter(Boolean);
const read = (p) => readFileSync(join(repo, p), 'utf8');
const lineCount = (text) => text.split('\n').length - (text.endsWith('\n') ? 1 : 0);
const lines = (list) => list.reduce((n, f) => n + lineCount(read(f)), 0);
const fmt = (n, d = 0) => n.toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d });
const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};
const sum = (xs) => xs.reduce((a, b) => a + b, 0);
const avg = (xs) => (xs.length ? sum(xs) / xs.length : 0);

const out = [];
const p = (s = '') => out.push(s);

const head = git('rev-parse', '--short', 'HEAD').trim();
p('# Numbers');
p();
p(`Generated by \`node evidence/measure.mjs <game repo>\` at game commit \`${head}\`. Every figure in CASE_STUDY.md and RESUME.md comes from this file.`);
p();

// --- Repository
const commits = Number(git('rev-list', '--count', 'HEAD').trim());
const dates = git('log', '--format=%ad', '--date=short').split('\n').filter(Boolean).sort();
const first = dates[0];
const last = dates[dates.length - 1];
const days = Math.round((Date.parse(last) - Date.parse(first)) / 86400000) + 1;
const weeks = {};
for (const w of git('log', '--format=%ad', '--date=format:%G-W%V').split('\n').filter(Boolean)) weeks[w] = (weeks[w] ?? 0) + 1;

const src = files('src/*.ts', 'src/**/*.ts', 'src/*.tsx', 'src/**/*.tsx');
const tests = files('tests/*.ts', 'tests/**/*.ts');
const testFiles = tests.filter((f) => /\.test\.ts$/.test(f));
const tools = files('tools/*.ts', 'tools/**/*.ts', 'src/cli/*.ts');
const md = files('*.md', '**/*.md');
const srcLines = lines(src);
const testLines = lines(tests);
const mdLines = lines(md);

const nowBlock = read('PROJECT_CONTEXT.md');
const gate = nowBlock.match(/`npm run check` (\d+)\/(\d+) in (\d+) test files/);

p('## Repository (`git ls-files`, `git log`)');
p();
p('| Measure | Value |');
p('| --- | --: |');
p(`| Commits | ${fmt(commits)} |`);
const subjects = git('log', '--format=%s').split('\n').filter(Boolean);
const unlinked = subjects.filter((s) => !/brief|handoff|merge|WP\d|plan|part [A-Z]|phase|step-back|playtest|register/i.test(s));
p(`| Commits naming their brief, plan, merge or phase | ${commits - unlinked.length} (the rest: ${unlinked.map((s) => `"${s}"`).join('; ')}) |`);
p(`| First / last commit | ${first} / ${last} (${days} days) |`);
p(`| TypeScript in \`src/\` | ${fmt(src.length)} files, ${fmt(srcLines)} lines |`);
p(`| TypeScript in \`tests/\` | ${fmt(tests.length)} files (${testFiles.length} \`*.test.ts\`), ${fmt(testLines)} lines |`);
p(`| CLI and workflow tools (\`src/cli\`, \`tools/\`) | ${fmt(tools.length)} files, ${fmt(lines(tools))} lines |`);
p(`| Tests passing at the last recorded gate (PROJECT_CONTEXT "Now") | ${gate ? `${gate[1]}/${gate[2]} in ${gate[3]} files` : 'not found'} |`);
p(`| Markdown | ${fmt(md.length)} files, ${fmt(mdLines)} lines |`);
p(`| Markdown lines per \`src/\` line | ${(mdLines / srcLines).toFixed(2)} |`);
p();
p('Commits per ISO week:');
p();
p('| Week | Commits |');
p('| --- | --: |');
for (const w of Object.keys(weeks).sort()) p(`| ${w} | ${weeks[w]} |`);
p();

// --- Process record
const briefFiles = files('docs/briefs/*', 'docs/archive/*').filter((f) => /\/\d{3}_[^/]*\.md$/.test(f));
const briefIds = new Set(briefFiles.map((f) => f.match(/\/(\d{3})_/)[1]));
const activeBriefs = files('docs/briefs/*').filter((f) => /\/\d{3}_[^/]*\.md$/.test(f));
const kinds = {};
for (const f of briefFiles) {
  const k = read(f).match(/\*\*Kind:\*\*\s*([a-z-]+)/i) ?? read(f).match(/^Kind:\s*([a-z-]+)/im);
  if (k) kinds[k[1].toLowerCase()] = (kinds[k[1].toLowerCase()] ?? 0) + 1;
}
const handoffsArchived = files('docs/archive/*').filter((f) => /SESSION_HANDOFF_[^/]*\.md$/.test(f));
const handoffsOpen = files('docs/*').filter((f) => /^docs\/SESSION_HANDOFF_[^/]*\.md$/.test(f));
const skills = files('.claude/skills/*').filter((f) => /SKILL\.md$/.test(f));
const modelChoice = read('docs/MODEL_CHOICE.md');
const outsideRuns = new Set([...modelChoice.matchAll(/^\| \d{4}-\d{2}-\d{2} \| (R\d+) \|/gm)].map((m) => m[1]));
// Outside runs from R9, the first after the owner made the Codex cold read standing (2026-10-25):
// how many raised items (N > 0), and how many had every item confirmed (Confirmed = N).
const outsideLater = [...modelChoice.matchAll(/^\| \d{4}-\d{2}-\d{2} \| R(\d+) \|([^\n]*)$/gm)]
  .map((m) => ({ run: Number(m[1]), cells: m[2].split('|').map((c) => c.trim()) }))
  .filter((r) => r.run >= 9)
  // cells after the run id: route, tool, wall, N, Confirmed, New, …
  .map((r) => ({ n: /^\d+$/.test(r.cells[3]) ? Number(r.cells[3]) : 0, confirmed: /^\d+$/.test(r.cells[4]) ? Number(r.cells[4]) : -1 }));
const outsideRaised = outsideLater.filter((r) => r.n > 0);
const outsideAllConfirmed = outsideRaised.filter((r) => r.confirmed === r.n);
const trialRows = [...modelChoice.split('## Trial log')[1].matchAll(/^\| \d{4}-\d{2}-\d{2} \|/gm)].length;
const registers = files('docs/playtests/*').filter((f) => /REGISTER\.md$/.test(f));
const findingIds = new Set();
for (const r of registers) for (const m of read(r).matchAll(/\bF(\d{2,3})\b/g)) findingIds.add(Number(m[1]));
const ideasRows = read('docs/IDEAS.md').split('\n').filter((l) => /^\| \d{4}-/.test(l)).length;
const changelogEntries = read('docs/archive/CHANGELOG.md').split('\n').filter((l) => /^- \d{4}-\d{2}-\d{2}/.test(l)).length;
const memDir = process.env.MEMORY_DIR;
const memoryFiles =
  memDir && existsSync(memDir) ? String(readdirSync(memDir).filter((f) => f.endsWith('.md') && f !== 'MEMORY.md').length) : 'n/a';

p('## Process record');
p();
p('| Measure | Value | Source |');
p('| --- | --: | --- |');
p(`| Briefs (numbered, all kinds) | ${briefIds.size} (${activeBriefs.length} active) | \`docs/briefs/\`, \`docs/archive/*/NNN_*.md\` |`);
p(`| Briefs by declared kind | ${Object.entries(kinds).sort().map(([k, n]) => `${k} ${n}`).join(', ')} | \`**Kind:**\` line (early briefs predate it) |`);
p(`| Session handoffs | ${handoffsArchived.length} archived + ${handoffsOpen.length} unmerged | \`docs/archive/*/SESSION_HANDOFF_*\` |`);
p(`| Changelog entries (dated) | ${changelogEntries} | \`docs/archive/CHANGELOG.md\` |`);
p(`| Skills | ${skills.length} | \`.claude/skills/*/SKILL.md\` |`);
p(`| Outside-agent reviews (Codex, Gemini) | ${outsideRuns.size} | MODEL_CHOICE → Outside log |`);
p(`| Outside runs from R9 (after the owner's 2026-10-25 decision) | ${outsideLater.length} runs; ${outsideRaised.length} raised items; ${outsideAllConfirmed.length} had every item confirmed | MODEL_CHOICE → Outside log (N and Confirmed columns) |`);
p(`| Model-routing trials | ${trialRows} | MODEL_CHOICE → Trial log |`);
p(`| Playtest findings | ${findingIds.size} (F${Math.min(...findingIds)}–F${Math.max(...findingIds)}) over ${registers.length} runs | \`docs/playtests/*/REGISTER.md\` |`);
p(`| Parked ideas | ${ideasRows} | \`docs/IDEAS.md\` |`);
p(`| Owner-preference memory files | ${memoryFiles} | Claude Code memory dir (set MEMORY_DIR) |`);
p();

// --- Ledger
const ledger = JSON.parse(read('docs/session-ledger.json'));
const rows = ledger.filter((r) => r.calls > 0).sort((a, b) => a.start.localeCompare(b.start));
// The game's committed list prices, re-priced at the kit's rates where evidence/reprice.mjs moved a
// row (audit finding 1); Claude Code's recorded figure only on a row with no list price.
const repricedPath = new URL('./game-repriced.json', import.meta.url);
const repriced = existsSync(repricedPath) ? JSON.parse(readFileSync(repricedPath, 'utf8')) : null;
if (repriced !== null && repriced.game !== head) {
  console.error(`evidence/game-repriced.json is for game commit ${repriced.game}, not ${head}: rerun evidence/reprice.mjs first`);
  process.exit(2);
}
const cost = (r) => repriced?.rows[r.id]?.to ?? r.listUSD ?? r.costUSD ?? 0;
p('## Session ledger (`docs/session-ledger.json`, written by `npm run sessions`)');
p();
p('Cost is list-price dollars from the token counts: a relative measure, since the work ran on a subscription.');
if (repriced !== null)
  p(
    `The game's ledger prices Sonnet 5.5 cache reads at twice the published rate, so the ${repriced.moved} rows with a Sonnet call are re-priced at the kit's rates (${repriced.rates.join('; ')}): $${fmt(repriced.fromUSD, 2)} → $${fmt(repriced.toUSD, 2)}, by \`${repriced.generatedBy}\` into \`evidence/game-repriced.json\`; ${repriced.notRepriced.length} such rows had no transcript left to re-price.`,
  );
p();
p('| Measure | Value |');
p('| --- | --: |');
p(`| Sessions | ${rows.length} (${rows[0].start.slice(0, 10)} → ${rows[rows.length - 1].start.slice(0, 10)}) |`);
p(`| Model calls | ${fmt(sum(rows.map((r) => r.calls)))} |`);
p(`| Tokens re-read from cache | ${fmt(sum(rows.map((r) => r.reReadM)) / 1000, 2)}B |`);
p(`| Cost (list price) | $${fmt(sum(rows.map(cost)))} |`);
p(`| Commits made in sessions | ${fmt(sum(rows.map((r) => r.commits ?? 0)))} |`);
p(`| Sessions with at least one flag | ${rows.filter((r) => (r.flags ?? []).length).length} |`);
p(`| Median peak context | ${fmt(median(rows.map((r) => r.peakK)))}k |`);
p(`| Sessions peaking over 250k | ${rows.filter((r) => r.peakK > 250).length} (${Math.round((100 * rows.filter((r) => r.peakK > 250).length) / rows.length)}%) |`);
p(`| Median cost per session | $${fmt(median(rows.map(cost)), 2)} |`);
const models = {};
for (const r of rows) models[r.model] = (models[r.model] ?? 0) + 1;
p(`| Sessions by model | ${Object.entries(models).sort((a, b) => b[1] - a[1]).map(([m, n]) => `${m} ${n}`).join(', ')} |`);
p();

const band = (label, rs) =>
  `| ${label} | ${rs.length} | ${fmt(avg(rs.map((r) => r.peakK)))}k | ${fmt(median(rs.map((r) => r.peakK)))}k | ${fmt(avg(rs.map((r) => r.reReadM)), 1)}M | ${fmt(avg(rs.map((r) => r.calls)))} | $${fmt(avg(rs.map(cost)), 2)} | ${Math.round((100 * rs.filter((r) => r.peakK > 250).length) / rs.length)}% |`;
const hdr = '| Group | Sessions | Avg peak | Median peak | Avg re-read | Avg calls | Avg cost | Peak > 250k |\n| --- | --: | --: | --: | --: | --: | --: | --: |';

p('### By month');
p();
p(hdr);
const months = [...new Set(rows.map((r) => r.start.slice(0, 7)))];
for (const m of months) p(band(m, rows.filter((r) => r.start.startsWith(m))));
p();

// The session-economy rules (ledger, hook, parts) landed in commit 66f07aa on 2026-10-02.
const cut = '2026-10-02';
p(`### Before and after the session-economy rules (ledger + hook + briefs in parts, ${cut}, \`66f07aa\`)`);
p();
p(hdr);
p(band(`before ${cut}`, rows.filter((r) => r.start.slice(0, 10) < cut)));
p(band(`from ${cut}`, rows.filter((r) => r.start.slice(0, 10) >= cut)));
p();

p('### Largest sessions by peak context');
p();
p('| Date | Title | Calls | Peak | Re-read | Cost | Commits | Flags |');
p('| --- | --- | --: | --: | --: | --: | --: | --- |');
for (const r of [...rows].sort((a, b) => b.peakK - a.peakK || a.start.localeCompare(b.start)).slice(0, 3)) {
  p(`| ${r.start.slice(0, 10)} | ${r.title} | ${r.calls} | ${r.peakK}k | ${r.reReadM}M | $${fmt(cost(r), 2)} | ${r.commits ?? 0} | ${(r.flags ?? []).join('; ')} |`);
}
p();

// --- Quoted, not recomputed
p('## Quoted from the game repo (computed by its own scripts; not recomputed here)');
p();
const docs1 = read('docs/codebase/1_DOCS.md');
const perBrief = docs1.match(/the median implementation brief is[^.]*\.[^.]*\./);
p(`- Spend by session kind, from \`docs/codebase/1_DOCS.md\` §5 (\`node docs/codebase/measure/session-kinds.mjs\`, 2026-11-07):`);
p();
const table = docs1.replace(/\r\n/g, '\n').split('**Where the spend went**')[1]?.split('\n\n')[1];
if (table) for (const l of table.split('\n')) p(l);
p();
if (perBrief) p(`- Per package (\`measure/per-brief.mjs\`): "${perBrief[0]}"`);
const churn = docs1.match(/Implementation briefs changed about one line of docs per line of `src\/` \([^)]*\)\./);
if (churn) p(`- Doc churn (same script): "${churn[0]}"`);
const toolsShare = docs1.match(/`src\/cli` alone is [^\n]*nearly half the source/);
if (toolsShare) p(`- Tooling share (\`docs/codebase/1_DOCS.md\`, 2026-11-07): "${toolsShare[0]}"`);
const diet = read('docs/archive/CHANGELOG.md').match(/doc diet\. `PROJECT_CONTEXT\.md` [\d,]+ → [\d,]+ chars/);
if (diet) p(`- The 2026-10-12 doc diet (CHANGELOG): "${diet[0]}"`);
p();

process.stdout.write(out.join('\n') + '\n');
