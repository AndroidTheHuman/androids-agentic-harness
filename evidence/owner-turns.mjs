// Extracts the owner's own prompts from Claude Code transcripts (read-only).
//
//   node evidence/owner-turns.mjs <transcript folder> [<transcript folder> …]
//     e.g. node evidence/owner-turns.mjs ~/.claude/projects/c--Users-xande-infinity-autobattler
//
// A transcript folder is ~/.claude/projects/<project slug>/. For each folder this writes
// evidence/private/owner-turns-<slug>.md (git-ignored: it holds raw prompts) with every human
// prompt, oldest first, under its session id and time, and prints the counts. A human prompt is
// what tools/sessionMeasures.ts's isHumanPrompt says it is: the same rule the ledger counts by.
// Sub-agent transcripts (<id>/subagents/) are not read: their prompts are written by a session.

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { isHumanPrompt } from '../tools/sessionMeasures.ts';

const OUT = resolve(import.meta.dirname, 'private');

function parse(text) {
  const out = [];
  for (const line of text.split('\n')) {
    if (line.trim() === '') continue;
    try {
      out.push(JSON.parse(line));
    } catch {
      // a partial last line
    }
  }
  return out;
}

function promptText(e) {
  const c = e.message?.content;
  if (typeof c === 'string') return c;
  return (c ?? [])
    .filter((b) => b.type === 'text')
    .map((b) => b.text ?? '')
    .join('\n');
}

const folders = process.argv.slice(2);
if (folders.length === 0) {
  console.error('usage: node evidence/owner-turns.mjs <transcript folder> [<transcript folder> …]');
  process.exit(1);
}
mkdirSync(OUT, { recursive: true });

for (const folder of folders) {
  if (!existsSync(folder)) {
    console.error(`no such folder: ${folder}`);
    process.exitCode = 1;
    continue;
  }
  const slug = basename(resolve(folder));
  const turns = [];
  let sessions = 0;
  for (const f of readdirSync(folder)) {
    if (!f.endsWith('.jsonl')) continue;
    const id = f.slice(0, -'.jsonl'.length);
    const entries = parse(readFileSync(join(folder, f), 'utf8'));
    const mine = entries.filter((e) => isHumanPrompt(e) && e.timestamp !== undefined);
    if (mine.length > 0) sessions++;
    let title = '';
    for (const e of entries) if (e.type === 'ai-title' && e.aiTitle !== undefined) title = e.aiTitle;
    mine.forEach((e, i) => turns.push({ id, title, at: e.timestamp, n: i + 1, text: promptText(e).trim() }));
  }
  turns.sort((a, b) => (a.at < b.at ? -1 : a.at > b.at ? 1 : a.n - b.n));
  const chars = turns.reduce((s, t) => s + t.text.length, 0);
  const first = turns[0]?.at.slice(0, 10) ?? '—';
  const last = turns.at(-1)?.at.slice(0, 10) ?? '—';
  const body = turns
    .map((t) => `## ${t.at.slice(0, 16).replace('T', ' ')} · ${t.id.slice(0, 8)} · prompt ${t.n} · ${t.title}\n\n${t.text}\n`)
    .join('\n');
  const file = join(OUT, `owner-turns-${slug}.md`);
  writeFileSync(
    file,
    `# Owner turns: ${slug}\n\nGenerated by \`node evidence/owner-turns.mjs\`; raw prompts, not for publication. ` +
      `${turns.length} prompts in ${sessions} sessions, ${first} → ${last}, ${chars} characters.\n\n${body}`,
  );
  console.log(`${slug}: ${turns.length} prompts in ${sessions} sessions, ${first} → ${last}, ${chars} characters → ${file}`);
}
